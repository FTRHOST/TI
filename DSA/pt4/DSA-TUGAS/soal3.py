nilai = 2 
total = 0

print("==== Berikut angka kelipatan 2 dari 1 sampai 50: ====")
# Melakukan loop untuk menampilkan bilangan kelipatan 2 dari 1 sampai 50
while nilai <= 50:
    print(nilai) # Menampilkan Semua nilai yang memenuhi syarat
    total += nilai # memasukan nilai ke variable total
    nilai += 2 # Untuk kelipatan 2


print(f'total dari semua penjumlahan bilangan kelipatan 2 daari 1 sampai 50 adalah: {total}')
