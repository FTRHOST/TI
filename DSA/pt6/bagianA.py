# Pecat Tidak Hormat dengan Kode Etik (PTDH) VT viral
print("====== Pecat Tidak Hormat dengan Kode Etik (PTDH) VT Viral ======");
ptdh = [];

# Memasukan minimal 5 data
ptdh.append("Kamu Resersi");
ptdh.append("Muda Sudah");
ptdh.append("Bersifat Seferti Ini");
ptdh.append("Apalagi Kalau Sudah Tua")
ptdh.append("Tidak fantast");

print("\nPTDH kamu yaa: ", ptdh);

# Pop (Hapus data terakhir) minimal 2 kali
ptdh.pop();
print("\nHapus Tidak Fantastnya: ", ptdh);

ptdh.pop()
print("\nHapus Apalagi Kalau Sudah Tuanya: ", ptdh);
